-- ===== limits (spec 011: 20 saved searches, 100 watched names per user) =====
create function public.enforce_user_limit() returns trigger
language plpgsql
set search_path = ''
as $$
declare
  max_rows int := tg_argv[0]::int;
  n int;
begin
  perform pg_advisory_xact_lock(hashtext(tg_table_name || new.user_id::text));
  execute format('select count(*) from public.%I where user_id = $1', tg_table_name) into n using new.user_id;
  if n >= max_rows then
    raise exception 'limit_reached: at most % rows in %', max_rows, tg_table_name using errcode = 'P0001';
  end if;
  return new;
end;
$$;

create trigger saved_searches_limit before insert on public.saved_searches
  for each row execute function public.enforce_user_limit('20');
create trigger watchlist_limit before insert on public.watchlist
  for each row execute function public.enforce_user_limit('100');

-- ===== row level security: on for every table; no policy = no access for anon/authenticated =====
do $$
declare t record;
begin
  for t in select tablename from pg_tables where schemaname = 'public' loop
    execute format('alter table public.%I enable row level security', t.tablename);
  end loop;
end;
$$;

