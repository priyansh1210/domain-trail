-- ===== RPCs (service role only) =====
create function public.jev_usage_add(p_day date, p_tokens bigint, p_requests int, p_degraded boolean)
returns void
language sql
security definer
set search_path = ''
as $$
  insert into public.jev_usage as u (day, input_tokens, requests, searches, degraded_searches)
  values (p_day, p_tokens, p_requests, 1, case when p_degraded then 1 else 0 end)
  on conflict (day) do update set
    input_tokens = u.input_tokens + excluded.input_tokens,
    requests = u.requests + excluded.requests,
    searches = u.searches + 1,
    degraded_searches = u.degraded_searches + excluded.degraded_searches;
$$;

create function public.month_jev_tokens(p_month date) returns bigint
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(sum(input_tokens), 0)::bigint from public.jev_usage
  where day >= date_trunc('month', p_month)::date
    and day < (date_trunc('month', p_month) + interval '1 month')::date;
$$;

revoke execute on function public.jev_usage_add(date, bigint, int, boolean) from public, anon, authenticated;
revoke execute on function public.month_jev_tokens(date) from public, anon, authenticated;
grant execute on function public.jev_usage_add(date, bigint, int, boolean) to service_role;
grant execute on function public.month_jev_tokens(date) to service_role;
revoke execute on function public.enforce_user_limit() from public, anon, authenticated;
